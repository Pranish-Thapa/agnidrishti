"""Point-level hotspot export for the frontend geographic map.

Exports verified NASA FIRMS detection coordinates (latitude, longitude,
acquisition date/time, platform, brightness, FRP, confidence, day/night) that
survived the full normalization → QC → exact district-assignment chain.

Design notes
------------
* Records keep their platform identity; the frontend filters by layer and
  never merges platforms silently.
* SP (standard processing) and NRT records are exported separately and never
  mixed.
* Coordinates are rounded to 4 decimal places (~11 m) — display precision,
  not a claim of GPS accuracy.
* The compact positional-array format keeps payloads small (the whole
  historical record is ~12 MB across all files).
* Every export file carries contract_version, provenance and per-platform
  record counts so missing platforms are visible instead of silent.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from . import config, download, geometry, historical, manifests, normalize, qc, spatial

POINTS_DIR = config.PUBLIC_DATA_DIR / "points"

# Brightness field exported per sensor family (the primary thermal channel).
BRIGHTNESS_FIELD = {"modis": "brightness", "viirs": "bright_ti4"}


def _utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _provenance(provider: str) -> dict[str, Any]:
    return {
        "source": "NASA FIRMS active fire products (MOD14/MYD14 C6.1; VNP14IMG family)",
        "processing": "normalize -> qc -> exact district polygon assignment",
        "provider": provider,
        "note": (
            "Each record is one satellite hotspot detection, not a unique fire. "
            "Coordinates rounded to 4 decimals for display. Generated by "
            "python -m pipeline export-points."
        ),
    }


def _export_group(
    records: list[dict[str, Any]],
    provider: str,
    product: str,
    out_root: Path,
) -> dict[str, Any]:
    grouped: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for record in records:
        grouped[(record["district_id"], record["acq_date"][:4])].append(record)

    counts_summary: dict[str, Any] = {}
    files_written = 0
    for district_id in config.DISTRICT_ORDER:
        district_years = {year: recs for (d, year), recs in grouped.items() if d == district_id}
        all_years = sorted(district_years)
        platform_counts: Counter[str] = Counter()
        for recs in district_years.values():
            platform_counts.update(r["platform"] for r in recs)

        district_dir = out_root / district_id
        district_dir.mkdir(parents=True, exist_ok=True)
        for year, recs in sorted(district_years.items()):
            rows = []
            for r in sorted(recs, key=lambda x: (x["acq_date"], x["acq_time"] or "")):
                lat, lon = r["latitude"], r["longitude"]
                if lat is None or lon is None:
                    continue  # QC already excludes these; defensive only
                confidence = r.get("confidence")
                rows.append(
                    [
                        round(lat, 4),
                        round(lon, 4),
                        r["acq_date"][5:],        # MM-DD (year is in the filename)
                        r.get("acq_time"),
                        r["platform"],
                        round(r.get("brightness", {}).get(BRIGHTNESS_FIELD.get(
                            "modis" if r["sensor_id"] == "modis" else "viirs"
                        ) or "brightness", 0) or 0, 1),
                        round(r["frp"], 1) if r.get("frp") is not None else None,
                        confidence,
                        r.get("daynight"),
                    ]
                )
            payload = {
                "contract_version": config.CONTRACT_VERSION,
                "generated_at": _utc_now(),
                "provider": provider,
                "product": product,
                "district_id": district_id,
                "year": year,
                "brightness_field": {
                    "modis": "brightness",
                    "viirs": "bright_ti4",
                },
                "record_format": [
                    "latitude", "longitude", "acq_date (MM-DD)", "acq_time (UTC)",
                    "platform", "brightness", "frp (MW)", "confidence", "daynight",
                ],
                "platform_counts": dict(sorted(Counter(r[4] for r in rows).items())),
                "record_count": len(rows),
                "provenance": _provenance(provider),
                "records": rows,
            }
            manifests.write_json(district_dir / f"{year}.json", payload)
            files_written += 1

        counts_summary[district_id] = {
            "years": all_years,
            "platform_counts": dict(sorted(platform_counts.items())),
            "total_records": sum(platform_counts.values()),
        }

    return {"files": files_written, "districts": counts_summary}


def run_point_export() -> dict[str, Any]:
    """Export verified point-level detections for the frontend map.

    SP: every assigned standard-processing record (reuses the Task 04B loader
    so processing is identical to the published aggregates). NRT: the acquired
    public snapshot files processed through the same chain.
    """

    POINTS_DIR.mkdir(parents=True, exist_ok=True)

    # SP records: full historical standard-processing set.
    sp_records, _qc_report, _spatial = historical.load_historical_records()
    sp_result = _export_group(sp_records, "sp", "SP", POINTS_DIR / "sp")

    # NRT records: normalize + QC + assign the acquired NRT snapshot files.
    grouped = historical.load_area_entries()  # area-api only
    nrt_entries = []
    manifest = manifests.load_manifest(config.DOWNLOAD_MANIFEST)
    seen: set[str] = set()
    for entry in manifest.get("entries", []):
        if entry.get("provider") != "nrt" or entry.get("sensor_id") in seen:
            continue
        path = config.REPO_ROOT / entry.get("storage_path", "")
        if path.exists():
            nrt_entries.append((entry, path))
            seen.add(entry.get("sensor_id"))

    nrt_records: list[dict[str, Any]] = []
    for entry, path in nrt_entries:
        sensor_id = entry["sensor_id"]
        for record in normalize.normalize_file(path, sensor_id):
            record["_source_entry"] = entry.get("entry_id")
            nrt_records.append(record)
    nrt_clean, _nrt_qc = qc.run_qc(nrt_records)
    boundaries = geometry.load_boundaries()
    index = geometry.DistrictIndex(boundaries)
    nrt_assigned, _ = spatial.assign_study_areas(nrt_clean, index)
    nrt_result = _export_group(nrt_assigned, "nrt", "NRT", POINTS_DIR / "nrt")

    manifest_out = {
        "contract_version": config.CONTRACT_VERSION,
        "generated_at": _utc_now(),
        "sp": {"record_count": len(sp_records), **sp_result},
        "nrt": {"record_count": len(nrt_assigned), **nrt_result},
        "provenance": _provenance("sp+nrt"),
    }
    manifests.write_json(POINTS_DIR / "index.json", manifest_out)

    return {
        "sp_records": len(sp_records),
        "nrt_records": len(nrt_assigned),
        "files": sp_result["files"] + nrt_result["files"],
        "output": str(POINTS_DIR),
    }
